"""Signed firmware images for the secure bootloader (format version 1).

Layout of a slot image (see firmware/boot/image.h, docs/secure-boot.md):

    0x000  header: magic, header version, image size, image version,
           48 reserved zero bytes, 64-byte Ed25519 signature
    0x080  0xFF padding
    0x200  application binary (padded with 0xFF to a multiple of 4)

Signature: Ed25519 over b"SIGNER-LAB-FW1 " + SHA-512(header[0:64] + app).

The firmware signing key is separate from the device approval key: it is
held by whoever releases firmware (a developer, or CI), never by the
device.
"""

import hashlib
import os
import re
import struct
from dataclasses import dataclass
from pathlib import Path

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey,
    Ed25519PublicKey,
)

MAGIC = 0x49574653  # "SFWI"
HEADER_VERSION = 1
HEADER_SIZE = 0x200
SIGNED_HEADER = 64
PREFIX = b"SIGNER-LAB-FW1 "
SLOT_A_ADDRESS = 0x08020000
SLOT_SIZE = 0x20000
RAM_START = 0x20000000
RAM_END = 0x20020000
MAX_VERSION = 0xFFFFFFFF

SEED_PATTERN = re.compile(r"[0-9a-f]{64}")


@dataclass(frozen=True)
class ImageInfo:
    version: int
    size: int
    stack_pointer: int
    entry: int


def generate_key(path):
    """Create a new firmware signing key file (hex seed, mode 0600)."""
    seed = os.urandom(32)
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "w", encoding="ascii") as stream:
        stream.write(seed.hex() + "\n")
    return public_key_bytes(Ed25519PrivateKey.from_private_bytes(seed))


def load_private_key(path):
    text = Path(path).read_text(encoding="ascii").strip()
    if SEED_PATTERN.fullmatch(text) is None:
        raise ValueError("Firmware signing key must be 64 lowercase hex characters.")
    return Ed25519PrivateKey.from_private_bytes(bytes.fromhex(text))


def public_key_bytes(private_key):
    return private_key.public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw
    )


def public_key_c_header(public_key):
    """C header that compiles the public key into the bootloader."""
    values = ", ".join(f"0x{byte:02x}" for byte in public_key)
    return (
        "/* Generated by 'signer-lab firmware public-key'. Do not edit. */\n"
        "#ifndef FIRMWARE_PUBLIC_KEY_H\n"
        "#define FIRMWARE_PUBLIC_KEY_H\n\n"
        "#include <stdint.h>\n\n"
        f"static const uint8_t firmware_public_key[32] = {{ {values} }};\n\n"
        "#endif\n"
    )


def _message(signed_header, application):
    return PREFIX + hashlib.sha512(signed_header + application).digest()


def build_image(application, version, private_key, slot_size=SLOT_SIZE):
    """Return the complete slot image for an application binary."""
    if not isinstance(version, int) or isinstance(version, bool) or not (
        0 <= version <= MAX_VERSION
    ):
        raise ValueError("Firmware version must be an integer from 0 to 2^32 - 1.")

    application = bytes(application)
    application += b"\xff" * (-len(application) % 4)
    if not application or len(application) > slot_size - HEADER_SIZE:
        raise ValueError("Application is empty or does not fit in the slot.")

    signed_header = struct.pack("<IIII", MAGIC, HEADER_VERSION, len(application), version)
    signed_header += bytes(SIGNED_HEADER - len(signed_header))
    signature = private_key.sign(_message(signed_header, application))

    header = signed_header + signature
    return header + b"\xff" * (HEADER_SIZE - len(header)) + application


def verify_image(image, public_key, slot_address=SLOT_A_ADDRESS, slot_size=SLOT_SIZE):
    """Same checks as the bootloader. Raises ValueError, returns ImageInfo."""
    image = bytes(image)
    if len(image) < HEADER_SIZE:
        raise ValueError("Image is shorter than its header.")

    magic, header_version, size, version = struct.unpack_from("<IIII", image)
    if magic == 0xFFFFFFFF:
        raise ValueError("Slot is empty.")
    if magic != MAGIC or header_version != HEADER_VERSION or any(image[16:SIGNED_HEADER]):
        raise ValueError("Invalid image header.")
    if size == 0 or size % 4 or size > slot_size - HEADER_SIZE:
        raise ValueError("Invalid image size.")
    if len(image) < HEADER_SIZE + size:
        raise ValueError("Image is truncated.")

    application = image[HEADER_SIZE:HEADER_SIZE + size]
    signature = image[SIGNED_HEADER:SIGNED_HEADER + 64]
    try:
        Ed25519PublicKey.from_public_bytes(public_key).verify(
            signature, _message(image[:SIGNED_HEADER], application)
        )
    except InvalidSignature as error:
        raise ValueError("Invalid firmware signature.") from error

    stack_pointer, entry = struct.unpack_from("<II", application)
    code_start = slot_address + HEADER_SIZE
    if (
        not RAM_START + 4 <= stack_pointer <= RAM_END
        or stack_pointer % 8
        or not entry & 1
        or not code_start <= (entry & ~1) < code_start + size
    ):
        raise ValueError("Invalid vector table.")

    return ImageInfo(version, size, stack_pointer, entry)
